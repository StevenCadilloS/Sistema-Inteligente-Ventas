-- --------------- PRODUCTOS ---------------
--
-- Precios en centavos: S/2500.00 = 250000.

-- Sin imagen: cada producto muestra el icono de su categoria hasta que el
-- administrador suba una foto al bucket `productos` (ver 0005). Sembrar
-- nombres de archivo aqui solo servia para que la app pidiera 404s.
insert into productos (id_categoria, id_marca, nombre, descripcion,
                       precio_centavos, stock)
select c.id_categoria, m.id_marca, v.nombre, v.descripcion,
       v.precio_centavos, v.stock
  from (values
    ('Laptops',    'Lenovo',   'Laptop Lenovo IdeaPad',
     'Laptop para uso academico y oficina',  250000, 10),
    ('Laptops',    'HP',       'Laptop HP Pavilion',
     'Laptop para trabajo y estudio',        280000,  8),
    ('Celulares',  'Samsung',  'Samsung Galaxy A55',
     'Smartphone Samsung Galaxy',            150000, 15),
    ('Accesorios', 'Logitech', 'Mouse Logitech G203',
     'Mouse gamer',                           12000, 30),
    ('Accesorios', 'Logitech', 'Teclado Logitech K380',
     'Teclado inalambrico',                   18000, 20),
    ('Audifonos',  'Sony',     'Audifonos Sony WH-CH520',
     'Audifonos inalambricos',                25000, 12)
  ) as v(categoria, marca, nombre, descripcion, precio_centavos, stock)
  join categorias c on c.nombre = v.categoria
  join marcas     m on m.nombre = v.marca
 where not exists (select 1 from productos p where p.nombre = v.nombre);

-- --------------- OFERTAS ---------------
--
-- Porcentajes enteros: 10 = 10%. Los combos fijan el precio final en centavos.

insert into ofertas (id_admin, nombre, id_tipo, porcentaje_descuento,
                     precio_oferta_centavos, fecha_inicio, fecha_fin)
select a.id_admin, v.nombre, t.id_tipo, v.pct, v.precio,
       timestamptz '2026-09-01 00:00:00-05', timestamptz '2026-12-31 23:59:59-05'
  from (values
    ('steven@tienda.com', 'Descuento 10%', 'Descuento',   10, null::integer),
    ('steven@tienda.com', 'Descuento 20%', 'Descuento',   20, null),
    ('luis@tienda.com',   'Descuento 30%', 'Descuento',   30, null),
    ('luis@tienda.com',   'Combo Gamer',   'Combo',     null, 20000),
    ('steven@tienda.com', 'Combo Audio',   'Combo',     null, 35000)
  ) as v(correo, nombre, tipo, pct, precio)
  join administradores a on a.correo = v.correo
  join tipos_oferta    t on t.nombre = v.tipo
 where not exists (select 1 from ofertas o where o.nombre = v.nombre);

-- --------------- SECUENCIA DE OFERTAS POR PRODUCTO ---------------
--
-- El orden es la escalera por la que sube el sistema cuando la respuesta del
-- cliente es desfavorable: primero 10%, luego 20%, luego 30%. Un producto sin
-- filas aqui se queda siempre en su precio normal (README, regla 8).

insert into ofertas_productos (id_oferta, id_producto, orden, cantidad)
select o.id_oferta, p.id_producto, v.orden, v.cantidad
  from (values
    -- Laptop Lenovo: escalera completa de tres escalones
    ('Descuento 10%', 'Laptop Lenovo IdeaPad',   1, 1),
    ('Descuento 20%', 'Laptop Lenovo IdeaPad',   2, 1),
    ('Descuento 30%', 'Laptop Lenovo IdeaPad',   3, 1),

    -- Samsung Galaxy: dos escalones
    ('Descuento 10%', 'Samsung Galaxy A55',      1, 1),
    ('Descuento 20%', 'Samsung Galaxy A55',      2, 1),

    -- Mouse: un solo escalon de descuento, y ademas entra en el combo
    ('Descuento 10%', 'Mouse Logitech G203',     1, 1),
    ('Combo Gamer',   'Mouse Logitech G203',     2, 1),
    ('Combo Gamer',   'Teclado Logitech K380',   1, 1),

    -- Combo Audio
    ('Combo Audio',   'Audifonos Sony WH-CH520', 1, 1)
  ) as v(oferta, producto, orden, cantidad)
  join ofertas   o on o.nombre = v.oferta
  join productos p on p.nombre = v.producto
 where not exists (
   select 1 from ofertas_productos op
    where op.id_oferta = o.id_oferta and op.id_producto = p.id_producto
 );

