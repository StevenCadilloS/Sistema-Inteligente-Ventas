-- Los datos de llenado-datos.sql, con dos cambios:
--
--   1. Sin TRUNCATE. El original empezaba borrando diez tablas en cascada;
--      aplicado por equivocacion sobre una base con ventas reales, no hay
--      vuelta atras. Aqui cada insert es idempotente (`on conflict do
--      nothing`), asi que correr la semilla dos veces no duplica ni borra
--      nada. Para vaciar la base a proposito esta supabase/tests/limpiar.sql,
--      que hay que ejecutar a mano.
--
--   2. Precios en centavos enteros: 2500.00 -> 250000. Ver la nota 1 de
--      0001_esquema.sql.
--
-- Los IDs no se fuerzan: las columnas son `generated by default as identity`
-- y fijarlos a mano deja la secuencia atras, de modo que el primer producto
-- que cree el administrador desde el panel chocaria con la clave primaria.
-- Las relaciones se resuelven por nombre.
